'use strict';
// The DOM contract between index.html and the scripts.
//
// Issue #16: app.js did $('#context-menu').innerHTML = ... but no element with that id
// existed. The assignment threw a TypeError, so the context menu - and with it the only
// visible way to delete a device - could never open. Nothing in the test suite noticed,
// because the suite stubbed a DOM that returned whatever the code asked for.
//
// A stub DOM is exactly the wrong tool for this: it agrees with the code. This checks
// the real index.html instead, so a selector with no matching element fails the build.
const fs = require('fs');
const path = require('path');

let passed = 0, failed = 0;
function ok(cond, msg) {
  if (cond) { passed++; console.log('  \u2713 ' + msg); }
  else { failed++; console.error('  \u2717 ' + msg); }
}

const WEB = path.join(__dirname, '..', 'web');
const html = fs.readFileSync(path.join(WEB, 'index.html'), 'utf8');
const appjs = fs.readFileSync(path.join(WEB, 'app.js'), 'utf8');
const canvasjs = fs.readFileSync(path.join(WEB, 'canvas.js'), 'utf8');

function uniq(a) { return Array.from(new Set(a)); }

console.log('index.html defines the ids the scripts ask for:');
{
  // ids declared in the markup
  const declared = uniq((html.match(/\bid="([^"]+)"/g) || []).map(function (m) {
    return m.replace(/^id="/, '').replace(/"$/, '');
  }));
  // ids created by the scripts' own generated HTML (legitimately absent from the page)
  const generated = uniq((appjs + canvasjs).match(/\bid="([^"]+)"/g) || []).map(function (m) {
    return m.replace(/^id="/, '').replace(/"$/, '');
  });

  // selectors the scripts look up at runtime
  const queried = [];
  const patterns = [/\$\('#([A-Za-z0-9_-]+)'\)/g, /getElementById\('([A-Za-z0-9_-]+)'\)/g];
  for (const re of patterns) {
    let m;
    while ((m = re.exec(appjs + canvasjs)) !== null) queried.push(m[1]);
  }

  const missing = uniq(queried).filter(function (id) {
    return declared.indexOf(id) === -1 && generated.indexOf(id) === -1;
  });
  ok(missing.length === 0,
    'every #id the scripts query exists in the page or is generated by them' +
    (missing.length ? ' - missing: ' + missing.join(', ') : ''));

  ok(declared.indexOf('context-menu') !== -1, '#context-menu exists (issue #16)');
  ok(declared.indexOf('toast') !== -1, '#toast exists');
  ok(queried.length > 10, 'the check actually found selectors to verify (' + uniq(queried).length + ')');
}

console.log('\nThe page loads a stylesheet that exists, and only one:');
{
  const links = (html.match(/<link[^>]+href="([^"]+\.css)"/g) || []).map(function (m) {
    return /href="([^"]+)"/.exec(m)[1];
  });
  ok(links.length > 0, 'index.html links at least one stylesheet (' + links.join(', ') + ')');
  for (const href of links) {
    ok(fs.existsSync(path.join(WEB, href)), 'the linked stylesheet exists: ' + href);
  }
  // A second, unlinked stylesheet is how 56 lines of port-label CSS ended up dead: the
  // rules were written, reviewed and never loaded.
  const cssFiles = fs.readdirSync(WEB).filter(function (f) { return /\.css$/.test(f); });
  const unlinked = cssFiles.filter(function (f) { return links.indexOf(f) === -1; });
  ok(unlinked.length === 0,
    'no stylesheet is orphaned (unlinked): ' + (unlinked.length ? unlinked.join(', ') : 'none'));
}

console.log('\nThe canvas styling the scripts rely on is in the loaded stylesheet:');
{
  const css = fs.readFileSync(path.join(WEB, 'style.css'), 'utf8');
  // Classes the canvas emits; without rules the labels render at browser default size
  // and swamp the drawing.
  const needed = ['port-label', 'port-peer', 'port-lldp', 'legend', 'port'];
  for (const cls of needed) {
    ok(css.indexOf('.' + cls) !== -1, '.' + cls + ' has styling in style.css');
  }
  ok(/#context-menu/.test(css), 'the context menu has styling');
}

console.log('\nDeleting a device is reachable without a context menu:');
{
  ok(/id="btn-delete-device"/.test(appjs), 'the inspector renders a delete button');
  ok(/function bindDeviceDelete/.test(appjs), 'and binds it after each render');
  ok(/bindDeviceDelete\(\);/.test(appjs), 'the binding is actually called');
  ok(/DELETE/.test(appjs) && /\/devices\//.test(appjs), 'which reaches the DELETE route');
  ok(/if \(!menu\)/.test(appjs), 'the context menu degrades instead of throwing when absent');
}

console.log('\n' + passed + ' passed, ' + failed + ' failed');
process.exit(failed ? 1 : 0);
