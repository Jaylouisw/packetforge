'use strict';
// A keyword after `show` is matched the way a box matches it: in any case.
//
// IOS states the rule in its own words: "You can enter commands in uppercase, lowercase, or mixed case. Only
// passwords are case sensitive" and "Cisco IOS commands are generally case-insensitive" (Configuration
// Fundamentals Configuration Guide, Cisco IOS Release 15.1S, Using the Cisco IOS Command-Line Interface -
// https://www.cisco.com/c/en/us/td/docs/ios/fundamentals/configuration/guide/TIPs_Conversion/cf_15_1s_book/cf_cli-basics.html),
// and "Commands are not case-sensitive" (Software Configuration Guide for the Cisco 5900 Series Embedded
// Services Routers, IOS 15.2(4)GC, Using the Command Line -
// https://www.cisco.com/c/en/us/td/docs/solutions/GGSG-Engineering/15-4-3M/config-guide/Configuration-Guide/CLIintro.html).
//
// This console lowercased the first word of a `show` line only. `show ip ARP`, `show ip VRRP` and
// `show POWER INLINE` reached their doors (those words are compared lowercased), while the views dispatched by
// a literal comparison - nat, `interface brief`, route, dns, dhcp, ospf, bgp - refused `show ip ROUTE` as an
// unknown view, and `show ipv6 ND` and `show mac ADDRESS-TABLE` did the same. One console, two rules for the
// same class of word. The words after `show` are now compared through one lowercased copy of the line, and the
// *values* on that line - a port name, a MAC, a prefix - still keep the case they were typed in (whether a box
// also folds an interface name is a separate question, recorded in research/show-keyword-case.md).
const path = require('path');
const { Topology, Simulator } = require('../engine');
const { CliSession } = require('../engine/cli');
const { loadCatalog } = require('../devices/registry');

let passed = 0, failed = 0;
function ok(cond, msg, detail) {
  if (cond) { passed++; console.log('  \u2713 ' + msg); }
  else { failed++; console.error('  \u2717 ' + msg + (detail ? '  [' + detail + ']' : '')); }
}

// One newline character, spelled without an escape: this file is generated by the console's own tooling and a
// backslash-n in a patch string is a real newline, not the two characters a JS source file needs.
const NL = String.fromCharCode(10);

const catalog = loadCatalog(path.join(__dirname, '..', 'devices')).filter(function (s) { return !s.error; });
const ROUTER = catalog.filter(function (s) { return s.model === 'generic-router'; })[0];
const SWITCH = catalog.filter(function (s) { return s.model === 'generic-switch'; })[0];

// A router with two addressed ports and two static routes: `show ip route` prints a table with three codes in
// it, and `show ip interface brief` prints two rows, so "same answer" is a real comparison rather than two
// identical refusals.
function routerLab() {
  const topo = new Topology();
  const dev = topo.addDevice(ROUTER);
  const cli = new CliSession(dev, topo, new Simulator(topo));
  const ports = [...dev.interfaces.values()].filter(function (i) { return i.type === 'ethernet'; });
  cli.run('configure terminal');
  cli.run('interface ' + ports[0].name);
  cli.run('ip address 10.0.0.1 255.255.255.0');
  cli.run('no shutdown');
  cli.run('exit');
  cli.run('interface ' + ports[1].name);
  cli.run('ip address 10.5.0.1 255.255.0.0');
  cli.run('no shutdown');
  cli.run('exit');
  cli.run('ip route 10.9.0.0 255.255.0.0 10.0.0.254');
  cli.run('ip route 0.0.0.0 0.0.0.0 10.0.0.253');
  cli.run('end');
  return cli;
}

function say(cli, line) {
  return cli.run(line).output.join('\n');
}

const cli = routerLab();

console.log('');
console.log('The words after `show ip` reach the same view in any case:');
const SAME = [
  ['show ip route', 'show ip ROUTE'],
  ['show ip route', 'show IP ROUTE'],
  ['show ip route', 'SHOW IP ROUTE'],
  ['show ip interface brief', 'show ip interface BRIEF'],
  ['show ip interface brief', 'show ip INTERFACE brief'],
  ['show ip nat translations', 'show ip NAT translations'],
  ['show ip nat rules', 'show ip nat RULES'],
  ['show ip dhcp binding', 'show ip DHCP binding'],
  ['show ip dns zone', 'show ip DNS zone'],
  ['show ip ospf neighbor', 'show ip OSPF neighbor'],
  ['show ip bgp summary', 'show ip BGP summary']
];
for (const pair of SAME) {
  const lower = say(cli, pair[0]);
  const upper = say(cli, pair[1]);
  ok(lower === upper, '`' + pair[1] + '` answers exactly as `' + pair[0] + '`', upper.split('\n')[0]);
  ok(!/^% Invalid show command/m.test(upper), '`' + pair[1] + '` is not refused as an unknown view', upper.split('\n')[0]);
}

console.log('');
console.log('The answer is the real table, not a second empty one:');
const routeTable = say(cli, 'show ip ROUTE');
ok(/C\s+10\.0\.0\.0\/24/.test(routeTable), '`show ip ROUTE` prints the connected 10.0.0.0/24 row', routeTable.split('\n').slice(0, 6).join(' | '));
ok(/S\*\s+0\.0\.0\.0\/0/.test(routeTable), 'and the candidate default row', routeTable.split('\n').slice(0, 6).join(' | '));
const brief = say(cli, 'show ip interface BRIEF');
ok(/^Interface\s+IP-Address/m.test(brief), '`show ip interface BRIEF` prints the brief header', brief.split('\n')[0]);
ok(/10\.0\.0\.1/.test(brief), 'and the address it was given', brief.split('\n').slice(0, 4).join(' | '));

console.log('');
console.log('The two other words that were literal comparisons:');
ok(say(cli, 'show mac ADDRESS-TABLE') === say(cli, 'show mac address-table'),
  '`show mac ADDRESS-TABLE` reaches the table');
ok(say(cli, 'show ipv6 ND') === say(cli, 'show ipv6 nd'),
  '`show ipv6 ND` reaches the advertisement view');

console.log('');
console.log('A value keeps the case it was typed in:');
const stray = say(cli, 'show ip route EXTRA');
ok(/EXTRA/.test(stray), 'a stray argument after `show ip ROUTE` is quoted back as typed', stray);
const badMacWord = say(cli, 'show mac address-table FLURB');
ok(/FLURB/.test(badMacWord), 'so is a word `show mac address-table` cannot use', badMacWord);
const swTopo = new Topology();
const sw = swTopo.addDevice(SWITCH);
const swCli = new CliSession(sw, swTopo, new Simulator(swTopo));
// A name that reaches no port is quoted back in the spelling that was typed - the sentence is about the value,
// and the value was not folded.
const typedName = 'FA9/99';
const missing = swCli.run('show interfaces ' + typedName).output.join(NL);
ok(missing.indexOf(typedName) !== -1, 'a port name is quoted back as typed: `show interfaces ' + typedName + '`', missing);
// A name that does reach a port is resolved the way a box resolves it - case does not matter there either - and
// the block prints the panel's own spelling rather than the typed one.
const realName = [...sw.interfaces.keys()][0];
const found = swCli.run('show interfaces ' + realName.toUpperCase()).output.join(NL);
ok(found.indexOf(realName + ' ') === 0, 'and a real port is found from its upper-case spelling, printed canonically', found.split(NL)[0]);

console.log('');
console.log('An unknown word is still an unknown word:');
ok(/^% Invalid show command: ip FLURB$/m.test(say(cli, 'show ip FLURB')), '`show ip FLURB` is refused');
ok(/Ambiguous command/.test(say(cli, 'show i')), 'and a shared prefix is still ambiguous, not guessed');

console.log('');
console.log('The dispatcher compares one lowercased copy of the line:');
{
  const src = require('fs').readFileSync(path.join(__dirname, '..', 'engine', 'cli.js'), 'utf8');
  ok(/const kw = tokens\.map\(function \(t\)/.test(src), 'the `show` chain builds `kw`, one lowercased copy');
  const literals = src.match(/what === '(?:ip|ipv6|mac)' && tokens\[[12]\] ===/g) || [];
  ok(literals.length === 0, 'and no view branch compares the typed token against a lower-case literal', literals.join(', '));
  ok(/what === 'ip' && kw\[1\] === 'route'/.test(src), '`route` is one of the views compared through `kw`');
}

console.log('');
console.log('');
console.log(passed + ' passed, ' + failed + ' failed');
process.exit(failed ? 1 : 0);
