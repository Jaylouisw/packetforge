'use strict';
/**
 * convergence.js -- how long each control-plane process takes to finish.
 *
 * Every timer in this engine used to be validated and then never counted. `hello 10`,
 * `dead 40`, `advertise 1`, STP's `forward-delay 15` were all parsed, range-checked, and
 * discarded, because `computeStp()` blocked its ports and `computeOspf()` installed its routes
 * at t=0. The consequence was a lab that could not show the thing an operator actually watches:
 * power-on, then the seconds in which nothing works yet.
 *
 * This module answers one question, in milliseconds: **when is this process done?** It is pure -
 * it reads configuration and returns times, no state, no clock, no side effects. The simulator
 * decides what to do with the answer (see `Simulator.setRunTime`).
 *
 * The times are canonical, not measured:
 *
 *   STP     a port that will forward is not forwarding until it has been through Listening and
 *           Learning, one forward-delay each (802.1D defaults: 15 s + 15 s).
 *   OSPF    adjacency at first hello plus a DBD/LSDB exchange; routes after the SPF hold.
 *   VRRP    a master is only certain of its mastership after 3 advertisements plus skew
 *           (RFC 5798 §6.1), so that is when the group starts answering for the VIP.
 *   DHCP    a lease arrives after the four-message exchange, not with the cable.
 *
 * What this does NOT model, and does not pretend to: real-time interleaving. Nothing here runs a
 * clock during a run. A query is answered as of one instant, computed from the timers.
 */

const C = {
  // 802.1D defaults (§17.14): forward delay 15 s, max age 20 s, hello 2 s.
  stpForwardDelaySec: 15,
  stpMaxAgeSec: 20,
  stpHelloSec: 2,
  // RFC 2328 / common defaults on a broadcast segment.
  ospfHelloSec: 10,
  ospfDeadSec: 40,
  // DBD exchange and LSDB synchronisation after the first hello is heard.
  ospfExchangeSec: 1,
  // SPF hold before the first route from that adjacency reaches the table.
  ospfSpfDelaySec: 5,
  // RFC 5798 defaults: Advertisement_Interval 1 s.
  vrrpAdvertSec: 1,
  // The four-message DHCP exchange on a quiet segment.
  dhcpExchangeSec: 1
};

function num(v, dflt) {
  const n = Number(v);
  return Number.isFinite(n) && n >= 0 ? n : dflt;
}

// ---------------------------------------------------------------------------
// The timers, per process, with the device's own configuration winning over the default.

function stpTimers(dev) {
  const cfg = (dev && dev.config) || {};
  const fd = num(cfg.stpForwardDelaySec, C.stpForwardDelaySec);
  // A port's path to Forwarding is Listening then Learning: two forward delays.
  return {
    forwardDelaySec: fd,
    // The two numbers `show spanning-tree` prints beside the forward delay. They are returned here rather than
    // written into the report as literals because a box prints the timers it is *running*: a capture of
    // `spanning-tree vlan 1 max-age 10` shows `Max Age 10 sec` in both blocks, and this model's schedule already
    // waits out whatever `stpMaxAgeSec`/`stpHelloSec` say, so a report with the factory numbers in it would
    // contradict the box's own convergence (research/stp-timer-lines-source.md).
    helloSec: num(cfg.stpHelloSec, C.stpHelloSec),
    maxAgeSec: num(cfg.stpMaxAgeSec, C.stpMaxAgeSec),
    listenEndMs: fd * 1000,
    learnEndMs: fd * 2000,
    forwardAtMs: fd * 2000,
    maxAgeMs: num(cfg.stpMaxAgeSec, C.stpMaxAgeSec) * 1000
  };
}

// ---------------------------------------------------------------------------
// Whose timers are in force
//
// A bridge does not pace its own ports. The root advertises hello, forward delay and max age in every
// configuration BPDU, and a non-root adopts them: "BPDUs carry the configured Root Bridge Timers Values.
// These BPDUs are generated by the Root Bridge and forwarded out all Designated Ports, so eventually all
// switches in the Spanning Tree topology learn and use such Timers Values, ignoring local Timers Values"
// (Cisco Learning Network, "STP timers"). Cisco's timer guide says it from the other side - "each BPDU includes
// the hello, forward delay, and max age STP timers ... Effectively, only a timer that is configured on the root
// bridge of the STP is important" (doc 19120) - and howtonetwork spells out the consequence: "Non-Root Bridges
// are not concerned with locally configured timer values".
//
// So the forward delay that paces a port through Listening and Learning is the *root's*, on every bridge. This
// schedule used to read the answering device's own config, which made a lab whose root was given a 4 s forward
// delay converge at 8 s on the root and 30 s on every defaulted non-root - and the report, which prints the
// root's numbers on the Root ID line, disagreed with the schedule behind it (#1722).
// research/stp-root-timers-pace-the-tree.md.
function stpTimersInForce(dev, rootDev) {
  return (rootDev && rootDev !== dev) ? stpTimers(rootDev) : stpTimers(dev);
}

// ---------------------------------------------------------------------------
// The window: when the timers in force started running, not just which they are.
//
// #1722 settled *whose* numbers pace a non-root's ports. It did not settle *from when*, and a schedule with no
// start instant is one that can only be read as if every timer began at t=0. Two consequences, both visible in
// a lab after a cable moves at t=60 s:
//
//   - a port that was Blocking and is now forwarding was reported Forwarding at the instant of the change,
//     because `atMs >= forwardAtMs` compared a 60 s clock with an 8 s timer;
//   - a bridge that loses the root while its root port is still up - the BPDU stream stops rather than the port
//     going down - claimed to be root the same instant. 802.1D keeps the last configuration BPDU until Max Age,
//     and only then puts its ports through Listening and Learning.
//
// So the timers in force come with a start instant: the change, plus Max Age where the information has to age
// out first. A port whose own link went down loses its information at once - 802.1D discards a port's
// information when the port is disabled, there is nothing to age - which is why the Max Age wait is gated on
// the *old root port still being up*, not on "no path to the root".
// research/stp-root-timers-pace-the-tree.md.
function logicalPortMembers(dev, logicalName) {
  const out = [];
  if (!dev || !dev.interfaces || typeof dev.interfaces.values !== 'function') return out;
  for (const iface of dev.interfaces.values()) {
    let name = iface.name;
    if (typeof dev.lagFor === 'function') {
      const lag = dev.lagFor(iface.name);
      if (lag && lag.id !== undefined && lag.id !== null) name = 'lag-' + lag.id;
    }
    if (name === logicalName) out.push(iface);
  }
  return out;
}

// Is that logical port still plugged in and up? Shutting the port that carries the BPDUs stops them exactly as
// a cut upstream does, but a shut port's information is discarded rather than aged, so it does not hold.
function logicalPortUp(topo, dev, logicalName) {
  if (!topo || !topo.links || typeof topo.links.values !== 'function') return false;
  const members = logicalPortMembers(dev, logicalName);
  if (!members.length) return false;
  for (const link of topo.links.values()) {
    if (typeof link.isUp === 'function' ? !link.isUp() : link.state !== 'up') continue;
    for (const iface of members) {
      if (!iface.enabled) continue;
      const end = typeof link.endpoint === 'function' ? link.endpoint(dev.id, iface.name) : null;
      if (!end) continue;
      return true;
    }
  }
  return false;
}

// When this bridge's current set of timers started running, and what it waits out first.
//
// `stpBefore` is the election as it stood the instant before the change (the Simulator pins it), or null when
// there is no change to compare against. `fromMs` is the instant of the change.
function stpTimersWindow(topo, stp, stpBefore, dev, fromMs) {
  const from = Number.isFinite(Number(fromMs)) ? Number(fromMs) : 0;
  const rootDev = stpRootOf(topo, stp, dev);
  const timers = stpTimersInForce(dev, rootDev);
  const known = !!(dev && dev.id !== undefined);
  const now = (stp && stp.bridges && known) ? stp.bridges[dev.id] : null;
  const before = (stpBefore && stpBefore.ports && known) ? stpBefore.ports[dev.id] : null;
  const costBefore = (stpBefore && stpBefore.costs && known) ? stpBefore.costs[dev.id] : undefined;

  let holdMs = 0;
  let hold = null;
  const isolatedNow = !!(now && now.cost === Infinity);
  const heardBefore = costBefore !== undefined && costBefore !== Infinity &&
    stpBefore.rootKey !== null && stpBefore.rootKey !== undefined && stpBefore.rootKey !== dev.id;
  const rootPortBefore = before
    ? Object.keys(before).filter(function (n) { return before[n] && before[n].role === 'root'; })[0]
    : null;
  if (isolatedNow && heardBefore && rootPortBefore && logicalPortUp(topo, dev, rootPortBefore)) {
    // The max age in force is the one that was advertised: the old root's, not this box's own.
    const oldRoot = (topo && typeof topo.getDevice === 'function') ? topo.getDevice(stpBefore.rootKey) : null;
    const held = stpTimersInForce(dev, oldRoot);
    holdMs = held.maxAgeMs;
    hold = { rootPort: rootPortBefore, maxAgeSec: held.maxAgeSec, oldRoot: stpBefore.rootKey };
  }

  return {
    rootDev: rootDev,
    adopted: !!(rootDev && rootDev !== dev),
    timers: timers,
    holdMs: holdMs,
    hold: hold,
    // The instant the timers in force started counting, and the instant the last of them is done - absolute,
    // and as an offset from the change, which is the form `buildSchedule` adds its own base to.
    startedAtMs: from + holdMs,
    forwardAtMs: from + holdMs + timers.forwardAtMs,
    offsetMs: holdMs + timers.forwardAtMs
  };
}

// The sentence the schedule prints as the reason.
function stpWindowBasis(win) {
  if (win.hold) {
    return 'no BPDU for max-age ' + win.hold.maxAgeSec + ' s (root port ' + win.hold.rootPort +
      ' still up), then listening + learning (' + win.timers.forwardDelaySec + ' s forward-delay each)';
  }
  return 'listening + learning (' + win.timers.forwardDelaySec + ' s forward-delay each' +
    (win.adopted ? ', the root ' + (win.rootDev.name || win.rootDev.id) + "'s" : '') + ')';
}

// The device the election named root, as an object - or null when there is no election to read, when the
// topology cannot answer for a device, or when this bridge has no path to the root at all. That last case is
// the one that keeps its own timers honestly: nothing is advertising to it, so nothing replaces its config.
function stpRootOf(topo, stp, dev) {
  if (!stp || !stp.root || stp.root.key === undefined || stp.root.key === null) return null;
  const own = (stp.bridges && dev && dev.id !== undefined) ? stp.bridges[dev.id] : null;
  if (own && own.cost === Infinity) return null;
  if (!topo || typeof topo.getDevice !== 'function') return null;
  return topo.getDevice(stp.root.key) || null;
}

function ospfTimers(dev) {
  const ospf = (dev && dev.config && dev.config.ospf) || {};
  const hello = num(ospf.helloSec, C.ospfHelloSec);
  const exchange = num(ospf.exchangeSec, C.ospfExchangeSec);
  const spf = num(ospf.spfDelaySec, C.ospfSpfDelaySec);
  const adjMs = (hello + exchange) * 1000;
  return {
    helloSec: hello,
    deadSec: num(ospf.deadSec, C.ospfDeadSec),
    adjacentAtMs: adjMs,
    // The first hello goes out at t=0 (the instant the interface comes up), so the neighbour is
    // heard one hello later, and the exchange follows on that adjacency.
    routesAtMs: adjMs + spf * 1000
  };
}

function vrrpTimers(group, dev) {
  const g = group || {};
  const advert = num(g.advertSec, (g.advertCs !== undefined && g.advertCs !== null)
    ? Number(g.advertCs) / 100 : C.vrrpAdvertSec);
  // RFC 5798: Master_Down_Interval = 3 x Advertisement_Interval + Skew_Time,
  // Skew_Time = ((256 - priority) / 256) seconds. Priority 255 subverts it entirely.
  const priority = num(g.priority, 100);
  const skewSec = priority >= 255 ? 0 : (256 - priority) / 256;
  return {
    advertSec: advert,
    skewSec: skewSec,
    masterDownMs: (3 * advert + skewSec) * 1000
  };
}

function dhcpTimers(dev) {
  const cfg = (dev && dev.config) || {};
  return {
    exchangeSec: num(cfg.dhcpExchangeSec, C.dhcpExchangeSec),
    leaseAtMs: num(cfg.dhcpExchangeSec, C.dhcpExchangeSec) * 1000
  };
}

// ---------------------------------------------------------------------------
// Which processes does this device run at all?

function runsStp(dev) {
  // A node running the spanning tree is a bridge: it has ports to another bridge and it is not
  // a router doing L3 only. This mirrors the filter computeStp() uses.
  return !!(dev && typeof dev.isL2 === 'function' && dev.isL2());
}

function runsOspf(dev) {
  return !!(dev && dev.config && dev.config.ospf);
}

function vrrpGroupsOf(dev) {
  if (!dev || !dev.config) return [];
  const g = dev.config.vrrp;
  if (!g) return [];
  if (Array.isArray(g)) return g;
  if (typeof g === 'object') return Object.keys(g).map(function (k) { return g[k]; });
  return [];
}

function runsDhcpClient(dev) {
  if (!dev) return false;
  if (dev.dhcp) return true;
  for (const iface of (dev.interfaces ? dev.interfaces.values() : [])) {
    if (iface.dhcp) return true;
  }
  return false;
}

// ---------------------------------------------------------------------------
// The schedule.

/**
 * buildSchedule(topology, opts) -> {
 *   entries: [{ deviceId, device, process, readyAtMs, basis }],
 *   convergedAtMs,
 *   byProcess: { stp: ms, ospf: ms, ... }   // the last completion of each process
 * }
 */
function buildSchedule(topo, opts) {
  opts = opts || {};
  // `fromMs` re-bases the whole schedule at an instant. It is 0 for a lab that has just been
  // powered on, and the instant of the change for a lab where a cable was pulled: the timers run
  // again from there, which is the only honest way to say "the network is converging".
  const fromMs = Number.isFinite(Number(opts.fromMs)) ? Number(opts.fromMs) : 0;
  const entries = [];
  const devices = topo && topo.devices ? Array.from(topo.devices.values()) : [];

  for (const dev of devices) {
    if (runsStp(dev)) {
      // The root's timers, not this box's own: a non-root adopts what the root advertises (#1722). `opts.stp`
      // is the election's answer, which is the only thing that can say who the root is; without one the
      // schedule falls back to the device's own config, the same way the report falls back to its own line.
      // And they start running at the change, not at t=0 - after Max Age where the old information has to age
      // out first (`stpTimersWindow`).
      const win = stpTimersWindow(topo, opts.stp, opts.stpBefore, dev, fromMs);
      entries.push({
        deviceId: dev.id, device: dev, process: 'stp',
        readyAtMs: win.offsetMs,
        forwardDelaySec: win.timers.forwardDelaySec,
        basis: stpWindowBasis(win)
      });
    }
    if (runsOspf(dev)) {
      const t = ospfTimers(dev);
      entries.push({
        deviceId: dev.id, device: dev, process: 'ospf',
        readyAtMs: t.routesAtMs,
        basis: 'hello ' + t.helloSec + ' s + exchange, then SPF hold'
      });
    }
    if (runsDhcpClient(dev)) {
      const t = dhcpTimers(dev);
      entries.push({
        deviceId: dev.id, device: dev, process: 'dhcp',
        readyAtMs: t.leaseAtMs,
        basis: 'DISCOVER/OFFER/REQUEST/ACK'
      });
    }
    for (const group of vrrpGroupsOf(dev)) {
      const t = vrrpTimers(group, dev);
      entries.push({
        deviceId: dev.id, device: dev, process: 'vrrp',
        group: group.groupId !== undefined ? group.groupId : group.vrid,
        readyAtMs: t.masterDownMs,
        basis: '3 x advertise ' + t.advertSec + ' s + skew'
      });
    }
  }

  for (const e of entries) {
    e.readyAtMs = fromMs + e.readyAtMs;
    e.basis = e.basis + (fromMs ? ' (after the change at ' + fromMs + ' ms)' : '');
  }
  if (fromMs) {
    // The schedule is not worth reporting as "converged" before the change happened.
    entries.push({
      deviceId: null, device: { name: '(change)', id: null }, process: 'change',
      readyAtMs: fromMs, basis: 'the link state changed'
    });
  }

  entries.sort(function (a, b) {
    if (a.readyAtMs !== b.readyAtMs) return a.readyAtMs - b.readyAtMs;
    if (a.process !== b.process) return a.process < b.process ? -1 : 1;
    return String(a.deviceId) < String(b.deviceId) ? -1 : 1;
  });

  let convergedAtMs = 0;
  const byProcess = {};
  for (const e of entries) {
    if (e.readyAtMs > convergedAtMs) convergedAtMs = e.readyAtMs;
    if (!(e.process in byProcess) || e.readyAtMs > byProcess[e.process]) byProcess[e.process] = e.readyAtMs;
  }

  return { entries: entries, convergedAtMs: convergedAtMs, byProcess: byProcess, fromMs: fromMs };
}

// The instant one process on one device is done, or null if that device does not run it.
function readyAt(schedule, process, deviceId) {
  for (const e of schedule.entries) {
    if (e.process === process && e.deviceId === deviceId) return e.readyAtMs;
  }
  return null;
}

// Split a schedule at an instant: what has finished, and what has not.
function at(schedule, atMs) {
  const ready = [], pending = [];
  for (const e of schedule.entries) {
    (e.readyAtMs <= atMs ? ready : pending).push(e);
  }
  return { ready: ready, pending: pending, fullyConverged: pending.length === 0 };
}

// The STP state a port is in at an instant: 'forwarding', 'learning', 'listening' or 'blocking'.
// `willForward` is the steady state from the spanning tree computation (a port that is destined to
// forward is only in a transitional state; a port that is destined to block was never forwarding).
function stpPortStateAt(dev, willForward, atMs, timers, startedAtMs) {
  // `timers` is the set in force - on a non-root, the root's (`stpTimersInForce`). It defaults to the device's
  // own so a caller with no election in hand still gets an answer, but every caller that has one passes it,
  // or the port would be paced by a number the box is not running.
  //
  // `startedAtMs` is when those timers started counting. It defaults to 0 - power-on, which is what every
  // caller meant before there was a change to re-base at - and a caller asking about a port after a change
  // passes `stpTimersWindow().startedAtMs`, or the port is compared against a clock that began before the
  // change and reads Forwarding the instant the change lands.
  const t = (timers && Number.isFinite(Number(timers.forwardDelaySec))) ? timers : stpTimers(dev);
  if (!willForward) return 'blocking';
  const started = Number.isFinite(Number(startedAtMs)) ? Number(startedAtMs) : 0;
  const elapsed = Number(atMs) - started;
  if (elapsed >= t.forwardAtMs) return 'forwarding';
  if (elapsed >= t.learnEndMs - t.forwardDelaySec * 1000) return 'learning';
  return 'listening';
}

// A port drops traffic in every state but Forwarding. This is the fact that makes a lab able to
// show "the switch is up, the cable is green, and nothing passes yet".
function stpForwardsIn(state) {
  return state === 'forwarding';
}

