const path=require('path');
const {Topology,Simulator}=require('../engine');const {CliSession}=require('../engine/cli');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog(path.join(__dirname,'..','devices'));const SW=c.find(s=>s.model==='generic-switch');
const t=new Topology();const a=t.addDevice(SW),b=t.addDevice(SW);
a.name='SW1';b.name='SW2';
t.connect(a.id,'Fa0/1',b.id,'Fa0/1');
const sim=new Simulator(t);const mk=d=>{const s=new CliSession(d,t,sim);s.run('enable');return s;};
const s1=mk(a),s2=mk(b);
const show=(s,x)=>{const o=s.run(x).output;console.log('$ '+x);o.forEach(l=>console.log('  '+l));};
show(s1,'show lldp neighbors');
console.log('--- SW1 no lldp run');
s1.run('configure terminal');show(s1,'no lldp run');s1.run('end');
show(s1,'show lldp neighbors');
show(s2,'show lldp neighbors');
console.log('--- back on');
s1.run('configure terminal');show(s1,'lldp run');s1.run('end');
show(s1,'show lldp neighbors');
console.log('--- per-port receive off');
s1.run('configure terminal');s1.run('interface Fa0/1');
show(s1,'no lldp receive');
s1.run('end');
show(s1,'show lldp neighbors Fa0/1');
show(s1,'show lldp neighbors');
console.log('--- per-port transmit off on SW2');
s2.run('configure terminal');s2.run('interface Fa0/1');show(s2,'no lldp transmit');s2.run('end');
console.log('--- dump:');
s1.run('configure terminal');s1.run('interface Fa0/1');s1.run('no lldp transmit');s1.run('end');
s2.run('configure terminal');s2.run('no lldp run');s2.run('end');
console.log(s1.run('show running-config').output.filter(l=>/lldp|interface Fa0\/1/.test(l)).join('\n'));
console.log('-- SW2 dump:'); console.log(s2.run('show running-config').output.filter(l=>/lldp|hostname/.test(l)).join('\n'));
