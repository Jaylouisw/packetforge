const path=require('path');
const {Topology,Simulator}=require('../engine');const {CliSession}=require('../engine/cli');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog(path.join(__dirname,'..','devices'));const SW=c.find(s=>s.model==='generic-switch');
const t=new Topology();const s1=t.addDevice(SW),s2=t.addDevice(SW),s3=t.addDevice(SW);
s1.name='SW1';s2.name='SW2';s3.name='SW3';
t.connect(s1.id,'Fa0/1',s2.id,'Fa0/1');t.connect(s2.id,'Fa0/2',s3.id,'Fa0/1');t.connect(s3.id,'Fa0/2',s1.id,'Fa0/2');
const sim=new Simulator(t);const mk=d=>{const s=new CliSession(d,t,sim);s.run('enable');return s;};
const a=mk(s1),b=mk(s2),d3=mk(s3);
[a,b,d3].forEach((s,i)=>s.run('configure terminal','hostname SW'+(i+1),'end'));
sim.refreshControlPlanes && sim.refreshControlPlanes();
['SW1','SW2','SW3'].forEach((n,i)=>{const s=[a,b,d3][i];console.log('['+n+'] summary:');s.run('show spanning-tree summary').output.forEach(l=>console.log('  '+l));});
console.log('[SW3] root:');d3.run('show spanning-tree root').output.forEach(l=>console.log('  '+l));
console.log('[SW3] table:');d3.run('show spanning-tree').output.forEach(l=>console.log('  '+l));
