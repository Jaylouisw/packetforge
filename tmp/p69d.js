console.log('== root primary on SW3');
cfg(dd,['spanning-tree vlan 1 root primary']);
show(dd,'show spanning-tree');
console.log('== priority 4096 on SW2 beats 24576');
cfg(b,['spanning-tree vlan 1 priority 4096']);
show(dd,'show spanning-tree');
show(b,'show spanning-tree');
console.log('== cost 100 on SW3 Fa0/1 changes the path');
cfg(dd,['interface Fa0/1','spanning-tree cost 100','exit']);
show(dd,'show spanning-tree');
console.log('== refusals');
