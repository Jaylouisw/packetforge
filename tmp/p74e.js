const path=require('path');
const {Topology,Simulator}=require('../engine');const {CliSession}=require('../engine/cli');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog(path.join(__dirname,'..','devices'));
const R=c.find(s=>s.model==='generic-router'),SW=c.find(s=>s.model==='generic-switch'),PC=c.find(s=>s.model==='generic-pc');
// PC1 - SW1 - R1 - R2, so a smaller MTU on the router's inside port must break a ping.
const t=new Topology();const r1=t.addDevice(R),r2=t.addDevice(R),sw=t.addDevice(SW),pc=t.addDevice(PC);
r1.name='R1';r2.name='R2';sw.name='SW1';pc.name='PC1';
t.connect(pc.id,'eth0',sw.id,'Fa0/1');t.connect(sw.id,'Fa0/2',r1.id,'Gi0/0');t.connect(r1.id,'Gi0/1',r2.id,'Gi0/0');
const sim=new Simulator(t);const mk=d=>{const s=new CliSession(d,t,sim);s.run('enable');return s;};
const a=mk(r1),b=mk(r2),sp=mk(pc),s1=mk(sw);
const cfg=(s,cmds)=>{s.run('configure terminal');cmds.forEach(x=>{const o=s.run(x).output;if(o.some(l=>/^%/.test(l)))console.log('  REFUSED '+x+' => '+o.join(' / '));});s.run('end');};
cfg(a,['hostname R1','interface Gi0/0','ip address 10.0.0.1 255.255.255.0','exit','interface Gi0/1','ip address 10.9.0.1 255.255.255.0','exit','ip route 198.51.100.0 255.255.255.0 10.9.0.2']);
cfg(b,['hostname R2','interface Gi0/0','ip address 10.9.0.2 255.255.255.0','exit','interface Gi0/1','ip address 198.51.100.9 255.255.255.0','exit','ip route 10.0.0.0 255.255.255.0 10.9.0.1']);
cfg(sp,['hostname PC1','interface eth0','ip address 10.0.0.50 255.255.255.0','ip default-gateway 10.0.0.1','exit']);
console.log('ping with default MTU:', sp.run('ping 198.51.100.9 count 1').output.filter(l=>/Success/.test(l))[0]);
cfg(a,['interface Gi0/0','mtu 100','exit']);
console.log('ping after mtu 100 on Gi0/0:', sp.run('ping 198.51.100.9 count 1').output.filter(l=>/Success|percent/.test(l))[0]);
console.log('  drops:', a.run('show interfaces Gi0/0').output.filter(l=>/drops|MTU/.test(l)).join(' | '));
cfg(a,['interface Gi0/0','no mtu','exit']);
console.log('ping after no mtu:', sp.run('ping 198.51.100.9 count 1').output.filter(l=>/Success/.test(l))[0]);
console.log('\n--- show interfaces Gi0/0 (after speed/duplex):');
cfg(a,['interface Gi0/0','speed 100','duplex full','exit']);
a.run('show interfaces Gi0/0').output.slice(0,5).forEach(l=>console.log('  '+l));
console.log('\n--- show spanning-tree on the switch, before and after speed on its uplink:');
console.log(s1.run('show spanning-tree').output.filter(l=>/Fa0\/2|Cost|Root/.test(l)).join('\n  '));
cfg(s1,['interface Fa0/2','speed 100','exit']);
console.log('  after:');
console.log(s1.run('show spanning-tree').output.filter(l=>/Fa0\/2|Cost/.test(l)).join('\n  '));
console.log('\n--- dump:');
cfg(a,['interface Gi0/0','mtu 1400','speed 100','duplex full','exit']);
console.log(a.run('show running-config').output.filter(l=>/Gi0\/0|mtu|speed|duplex/.test(l)).join('\n  '));
console.log('\n--- refusals:');
cfg(a,['interface Gi0/0','mtu 64','mtu 99999','mtu abc','mtu','speed 10000','speed fast','duplex half','duplex sideways','no mtu extra','exit']);
