const {Topology,Simulator,CliSession}=require('../engine');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog('C:/Users/jay/packetforge/devices');
const R=c.find(s=>s.model==='generic-router'),SW=c.find(s=>s.model==='generic-switch'),PC=c.find(s=>s.model==='generic-pc');
const t=new Topology();const sw=t.addDevice(SW);sw.name='SW1';const r1=t.addDevice(R);r1.name='R1';const r2=t.addDevice(R);r2.name='R2';
const pc=t.addDevice(PC);pc.name='PC1';
const l1=t.connect(r1.id,'Gi0/0',sw.id,'Fa0/1');t.connect(r2.id,'Gi0/0',sw.id,'Fa0/2');t.connect(pc.id,'eth0',sw.id,'Fa0/3');
const sim=new Simulator(t);
const cfg=(d,cmds)=>{const s=new CliSession(d,t,sim);s.run('enable');s.run('configure terminal');for(const x of cmds){const o=s.run(x).output;if(o.some(l=>/^%/.test(l)))console.log('  REFUSED ['+d.name+'] '+x+' => '+o[0]);}s.run('end');return s;};
const s1=cfg(r1,['interface Gi0/0','ip address 192.168.9.2 255.255.255.0','vrrp 1 ip 192.168.9.1','vrrp 1 priority 150','vrrp 1 preempt','exit']);
const s2=cfg(r2,['interface Gi0/0','ip address 192.168.9.3 255.255.255.0','vrrp 1 ip 192.168.9.1','vrrp 1 priority 100','exit']);
const sp=cfg(pc,['interface eth0','ip address 192.168.9.50 255.255.255.0','ip default-gateway 192.168.9.1','exit']);
const rate=(o)=>{const m=/Success rate is (\d+) percent/.exec(o.join(' '));return m?m[1]+'%':'?';};
const show=(s,x)=>{console.log('['+s.device.name+'] $ '+x);const o=s.run(x).output;o.forEach(l=>console.log('   '+l));if(!o.length)console.log('   (SILENT)');};
console.log('PC1 -> VIP       :', rate(sp.run('ping 192.168.9.1 count 2').output));
console.log('R1 -> VIP        :', rate(s1.run('ping 192.168.9.1 count 2').output));
console.log('PC1 -> R1 real   :', rate(sp.run('ping 192.168.9.2 count 2').output));
console.log('PC1 -> R2 real   :', rate(sp.run('ping 192.168.9.3 count 2').output));
show(s2,'show vrrp');
console.log('--- pull R1 cable');
s1.run('link down '+l1.id);
show(s1,'show vrrp'); show(s2,'show vrrp');
console.log('PC1 -> VIP after failover:', rate(sp.run('ping 192.168.9.1 count 2').output));
show(s2,'show vrrp');
