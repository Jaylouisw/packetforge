const {Topology,Simulator,CliSession}=require('../engine');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog('C:/Users/jay/packetforge/devices');const R=c.find(s=>s.model==='generic-router'),SW=c.find(s=>s.model==='generic-switch'),PC=c.find(s=>s.model==='generic-pc');
const t=new Topology();const r1=t.addDevice(R);r1.name='R1';const sw=t.addDevice(SW);sw.name='SW1';const pc=t.addDevice(PC);pc.name='PC1';
t.connect(r1.id,'Gi0/0',sw.id,'Fa0/1');t.connect(sw.id,'Fa0/2',pc.id,'eth0');const sim=new Simulator(t);
const cfg=(d,cmds)=>{const s=new CliSession(d,t,sim);s.run('enable');s.run('configure terminal');for(const x of cmds)s.run(x);s.run('end');return s;};
cfg(r1,['interface Gi0/0','ip address 10.0.0.1 255.255.255.0','exit']);
cfg(pc,['interface eth0','ip address 10.0.0.10 255.255.255.0','exit','ip default-gateway 10.0.0.1']);
const s=cfg(r1,[]),swc=cfg(sw,[]);
s.run('ping 10.0.0.10 count 2');
const show=(p,cmd)=>{console.log(p+cmd); (p[0]==='S'?swc:s).run(cmd).output.forEach(l=>console.log(l));};
show('R1#','show arp');
show('R1#','clear arp');
show('R1#','show arp');
show('R1#','clear arp');
show('SW1#','show mac address-table');
show('SW1#','clear mac address-table');
show('SW1#','show mac address-table');
show('R1#','clear mac address-table');
show('R1#','clear ip route *');
