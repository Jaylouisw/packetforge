const path=require('path');
const {Topology,Simulator}=require('../engine');const {CliSession}=require('../engine/cli');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog(path.join(__dirname,'..','devices'));const R=c.find(s=>s.model==='generic-router');
const t=new Topology();const r=t.addDevice(R);r.name='R1';const sim=new Simulator(t);
const s=new CliSession(r,t,sim);s.run('enable');s.run('configure terminal');s.run('interface Gi0/0');
console.log('mode:',s.mode);
console.log('ip add  ->',JSON.stringify(s._expandAbbrev(['ip','add','10.1.1.1','255.255.255.0'])));
console.log('ip hel  ->',JSON.stringify(s._expandAbbrev(['ip','hel','10.1.1.9'])));
const cfgForms=s._helpForms('config').filter(f=>String(f[0]).toLowerCase()==='ip');
console.log('config ip forms:',JSON.stringify(cfgForms.map(f=>f.slice(0,2))));
