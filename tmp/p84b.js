const path=require('path');
const {Topology,Simulator}=require('../engine');const {CliSession}=require('../engine/cli');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog(path.join(__dirname,'..','devices'));
const SW=c.find(s=>s.model==='generic-switch'), R=c.find(s=>s.model==='generic-router');
const t=new Topology();const a=t.addDevice(SW),b=t.addDevice(SW),r=t.addDevice(R);
a.name='SW1';b.name='SW2';r.name='R1';
const ap=Array.from(a.interfaces.keys()).filter(n=>!a.interfaces.get(n).svi);
t.connect(a.id,ap[0],b.id,ap[0]);
t.connect(a.id,ap[1],r.id,'Gi0/0');
const sim=new Simulator(t);
const s=new CliSession(a,t,sim);s.run('enable');
const show=(cmd)=>{console.log('$ '+cmd);s.run(cmd).output.forEach(l=>console.log('  '+l));};
show('show lldp');
show('show lldp neighbors');
show('show lldp neighbors detail');
show('show lldp interface');
show('show lldp traffic');
show('show lldp traffic '+ap[0]);
console.log('== after no lldp transmit on a port + traffic again');
s.run('configure terminal');s.run('interface '+ap[0]);s.run('no lldp transmit');s.run('end');
s.run('show lldp interface').output.forEach(l=>console.log('  '+l));
show('show lldp neighbors detail extra');
