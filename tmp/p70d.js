const {Topology,Simulator,CliSession}=require('../engine');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog('C:/Users/jay/packetforge/devices');const R=c.find(s=>s.model==='generic-router'),PC=c.find(s=>s.model==='generic-pc'),SW=c.find(s=>s.model==='generic-switch');
const t=new Topology();const r1=t.addDevice(R);r1.name='R1';const sw=t.addDevice(SW);sw.name='SW1';const pc=t.addDevice(PC);pc.name='PC1';
t.connect(pc.id,'eth0',sw.id,'Fa0/1');t.connect(sw.id,'Fa0/2',r1.id,'Gi0/0');
const sim=new Simulator(t);
const s1=new CliSession(r1,t,sim);s1.run('enable');
s1.run('configure terminal','interface Gi0/0','ip address 10.0.0.1 255.255.255.0','exit');
s1.run('ip access-list extended BLOCK','deny icmp any host 10.0.0.99','permit ip any any','exit','end');
s1.run('configure terminal','interface Gi0/0','ip access-group BLOCK in','exit','end');
const sp=new CliSession(pc,t,sim);sp.run('enable');
sp.run('configure terminal','interface eth0','ip address 10.0.0.50 255.255.255.0','ip default-gateway 10.0.0.1','exit','end');
const r99=sp.run('ping 10.0.0.99 count 3').output.filter(l=>/Success/.test(l));
const r1p=sp.run('ping 10.0.0.1 count 2').output.filter(l=>/Success/.test(l));
console.log('ping .99:', r99); console.log('ping .1 :', r1p);
s1.run('show access-lists').output.forEach(l=>console.log('  '+l));
console.log('drops:', JSON.stringify(sim.events.filter(e=>e.type==='drop').slice(-4).map(e=>({r:e.reason,a:e.acl}))));
