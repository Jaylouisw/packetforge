const {Topology,Simulator,CliSession}=require('../engine');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog('C:/Users/jay/packetforge/devices');const R=c.find(s=>s.model==='generic-router'),PC=c.find(s=>s.model==='generic-pc'),SW=c.find(s=>s.model==='generic-switch');
// PC1 -- SW1 -- R1 (inside Gi0/0)  -- R2 (10.9.0.0/24) -- 10.1.0.0/24 outside
const t=new Topology();const r1=t.addDevice(R),r2=t.addDevice(R),sw=t.addDevice(SW),pc=t.addDevice(PC);
r1.name='R1';r2.name='R2';sw.name='SW1';pc.name='PC1';
t.connect(pc.id,'eth0',sw.id,'Fa0/1');t.connect(sw.id,'Fa0/2',r1.id,'Gi0/0');t.connect(r1.id,'Gi0/1',r2.id,'Gi0/0');
const sim=new Simulator(t);const mk=d=>{const s=new CliSession(d,t,sim);s.run('enable');return s;};
const a=mk(r1),b=mk(r2),sp=mk(pc);
const cfg=(s,cmds)=>{s.run('configure terminal');cmds.forEach(x=>{const o=s.run(x).output;if(o.some(l=>/^%/.test(l)))console.log('  REFUSED ['+(s.device.config.hostname||s.device.name)+'] '+x+' => '+o.join(' / '));});s.run('end');};
cfg(a,['hostname R1','interface Gi0/0','ip address 10.0.0.1 255.255.255.0','exit','interface Gi0/1','ip address 203.0.113.2 255.255.255.0','exit','ip route 0.0.0.0 0.0.0.0 203.0.113.254']);
cfg(b,['hostname R2','interface Gi0/0','ip address 203.0.113.254 255.255.255.0','exit','interface Gi0/1','ip address 198.51.100.9 255.255.255.0','exit']);
cfg(sp,['hostname PC1','interface eth0','ip address 10.0.0.50 255.255.255.0','ip default-gateway 10.0.0.1','exit']);
console.log('ping before nat:', sp.run('ping 198.51.100.9 count 1').output.filter(l=>/Success/.test(l))[0]);
console.log('--- configure PAT');
cfg(a,['access-list 1 permit 10.0.0.0 0.0.0.255','interface Gi0/0','ip nat inside','exit','interface Gi0/1','ip nat outside','exit','ip nat inside source list 1 interface Gi0/1 overload']);
const show=(s,x)=>{console.log('['+(s.device.config.hostname||s.device.name)+'] $ '+x);const o=s.run(x).output;o.forEach(l=>console.log('   '+l));if(!o.length)console.log('   (SILENT)');};
show(a,'show ip nat statistics');
console.log('ping after nat:', sp.run('ping 198.51.100.9 count 2').output.filter(l=>/Success/.test(l))[0]);
show(a,'show ip nat translations');
show(a,'show running-config');
console.log('--- static');
cfg(a,['ip nat inside source static 10.0.0.50 203.0.113.50']);
show(a,'show ip nat translations');
console.log('--- refusals');
cfg(a,['ip nat inside source list 99 interface Gi0/1 overload','ip nat inside source list 1 interface Gi0/9 overload','ip nat inside source list 1 interface Gi0/0 overload','ip nat inside source static 10.0.0.50','ip nat outside source static 10.0.0.50 203.0.113.50','ip nat bogus']);
cfg(a,['interface Gi0/0','ip nat outside inside','no ip nat outside','exit']);
show(a,'show ip nat statistics');
console.log('--- removal');
console.log(a.run('configure terminal','no ip nat inside source' ).output.join(' | '));
console.log(a.run('no ip nat inside source static 10.0.0.50 203.0.113.50').output.join(' | '));
console.log(a.run('no ip nat inside source static 10.0.0.50 203.0.113.50').output.join(' | '));
console.log(a.run('exit').output.join(''));
show(a,'show ip nat statistics');
