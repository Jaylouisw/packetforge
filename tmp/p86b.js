const path=require('path');
const {Topology,Simulator}=require('../engine');const {CliSession}=require('../engine/cli');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog(path.join(__dirname,'..','devices'));const R=c.find(s=>s.model==='generic-router');
const t=new Topology();const r1=t.addDevice(R),r2=t.addDevice(R);r1.name='R1';r2.name='R2';
const p1=Array.from(r1.interfaces.keys()).filter(n=>!r1.interfaces.get(n).svi&&!r1.interfaces.get(n).parent);
const p2=Array.from(r2.interfaces.keys()).filter(n=>!r2.interfaces.get(n).svi&&!r2.interfaces.get(n).parent);
t.connect(r1.id,p1[0],r2.id,p2[0]);
const sim=new Simulator(t);
const mk=d=>{const s=new CliSession(d,t,sim);s.run('enable');return s;};
const a=mk(r1),b=mk(r2);
const cfg=(s,cm)=>{s.run('configure terminal');let o=[];for(const x of cm)o=o.concat(s.run(x).output);return o;};
console.log('== R1:');
cfg(a,['hostname R1','interface Gi0/0','ip address 10.0.0.1 255.255.255.0','exit']).forEach(l=>console.log('  '+l));
const enter=a.run('configure terminal');a.run('router ospf 1').output.forEach(l=>console.log('  '+l));
console.log('  prompt: '+a.prompt());
a.run('network 10.0.0.0 0.0.0.255 area 0').output.forEach(l=>console.log('  '+l));
a.run('router-id 1.1.1.1').output.forEach(l=>console.log('  '+l));
a.run('network 10.9.9.0 0.0.0.255 area 0').output.forEach(l=>console.log('  '+l));
a.run('bogus verb').output.forEach(l=>console.log('  '+l));
a.run('exit').output.forEach(l=>console.log('  '+l));
console.log('  prompt after exit: '+a.prompt());
a.run('end');
console.log('== R2 the same but area 1:');
cfg(b,['hostname R2','interface Gi0/0','ip address 10.0.0.2 255.255.255.0']);
b.run('configure terminal');b.run('router ospf 1');b.run('network 10.0.0.0 0.0.0.255 area 1');b.run('router-id 2.2.2.2');b.run('end');
console.log('  R1 neighbour:');a.run('show ip ospf neighbor').output.slice(0,5).forEach(l=>console.log('    '+l));
console.log('  agreement, same area:');
cfg(b,['router ospf 1']);
b.run('configure terminal');b.run('router ospf 1');b.run('network 10.0.0.0 0.0.0.255 area 0');b.run('end');
a.run('show ip ospf neighbor').output.slice(0,5).forEach(l=>console.log('    '+l));
console.log('== show ip ospf:');a.run('show ip ospf').output.slice(0,4).forEach(l=>console.log('  '+l));
console.log('== dump:');a.run('show running-config').output.filter(l=>/ospf|network|router-id/.test(l)).forEach(l=>console.log('  '+l));
