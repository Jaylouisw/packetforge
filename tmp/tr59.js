const {Topology,Simulator,CliSession}=require('../engine');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog('C:/Users/jay/packetforge/devices');const R=c.find(s=>s.model==='generic-router');
const t=new Topology();const d=t.addDevice(R);d.name='R1';const s=new CliSession(d,t,new Simulator(t));s.run('enable');
const p=(x,prompt)=>{console.log((prompt||'R1(config)#')+x);s.run(x).output.forEach(l=>console.log(l));};
s.run('configure terminal');
p('hostname');
p('dns zone lab.example');
p('dns add www.lab.example A abc');
p('dns add www.lab.example A 10.0.2.10');
p('dns add note.lab.example TXT hello world');
p('dns add mail.lab.example MX mail.lab.example');
p('dns add mail.lab.example MX 10 mail.lab.example');
p('ip dhcp pool lan');
p('network 10.0.0.0 255.255.255.0', 'R1(config-dhcp)#');
p('range 10.0.0.50 10.0.0.10', 'R1(config-dhcp)#');
p('default-router abc', 'R1(config-dhcp)#');
p('dns-server abc', 'R1(config-dhcp)#');
p('default-router 10.0.0.1', 'R1(config-dhcp)#');
p('range 10.0.0.10 10.0.0.50', 'R1(config-dhcp)#');
p('exit', 'R1(config-dhcp)#');
p('dns add br.lab.example A 10.0.0.5');
s.run('end');
console.log('R1#show dns'); s.run('show dns').output.forEach(l=>console.log(l));
console.log('R1#ping www.lab.example count 1'); s.run('ping www.lab.example count 1').output.forEach(l=>console.log(l));
console.log('R1#show running-config (dns/dhcp lines)'); s.run('show running-config').output.filter(l=>/^dns |^ip dhcp/.test(l)).forEach(l=>console.log(l));
