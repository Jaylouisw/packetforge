const path=require('path');
const {Topology,Simulator}=require('../engine');const {CliSession}=require('../engine/cli');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog(path.join(__dirname,'..','devices'));
const SW=c.find(s=>s.model==='generic-switch')||c.find(s=>s.kind==='switch'||/switch/i.test(s.model));
const PC=c.find(s=>s.model==='generic-pc');
console.log('switch model:', SW&&SW.model);
function lab(){
  const t=new Topology();const sw=t.addDevice(SW),p1=t.addDevice(PC),p2=t.addDevice(PC);
  sw.name='SW1';p1.name='PC1';p2.name='PC2';
  const ports=[...sw.interfaces.keys()].filter(n=>!sw.interfaces.get(n).svi);
  t.connect(p1.id,'eth0',sw.id,ports[0]);t.connect(p2.id,'eth0',sw.id,ports[1]);
  const sim=new Simulator(t);const mk=d=>{const s=new CliSession(d,t,sim);s.run('enable');return s;};
  const a=mk(sw),s1=mk(p1),s2=mk(p2);
  const cfg=(s,cm)=>{s.run('configure terminal');const o=[];for(const x of cm)o.push.apply(o,s.run(x).output);s.run('end');return o;};
  cfg(s1,['hostname PC1','interface eth0','ip address 10.0.0.50 255.255.255.0','exit']);
  cfg(s2,['hostname PC2','interface eth0','ip address 10.0.0.60 255.255.255.0','exit']);
  return {t,sim,sw,p1,p2,a,s1,s2,cfg,ports};
}
let e=lab();
const P0=e.ports[0], P1=e.ports[1];
console.log('ports:',P0,P1);
console.log('== enable:');
console.log(e.cfg(e.a,['interface '+P0,'switchport mode access','switchport port-security']).join('\n'));
console.log('== show port-security:'); e.a.run('show port-security').output.forEach(l=>console.log('  '+l));
console.log('== detail:'); e.a.run('show port-security interface '+P0).output.forEach(l=>console.log('  '+l));
console.log('== traffic from PC1 (allowed) then PC2 into P0 (violation, shutdown):');
console.log(e.s1.run('ping 10.0.0.60 count 1').output.filter(l=>/Success|Reply/.test(l)).join(' | '));
console.log(e.s2.run('ping 10.0.0.50 count 1').output.filter(l=>/Success|Reply/.test(l)).join(' | '));
console.log('== state:');
e.a.run('show port-security').output.forEach(l=>console.log('  '+l));
console.log('  -- interfaces status:'); e.a.run('show interfaces status').output.forEach(l=>console.log('   '+l));
console.log('  -- detail:'); e.a.run('show port-security interface '+P0).output.forEach(l=>console.log('   '+l));
console.log('== recover:');
console.log(e.cfg(e.a,['interface '+P0,'no shutdown']).join('\n'));
e.a.run('show port-security').output.forEach(l=>console.log('  '+l));
console.log('== addresses:'); e.a.run('show port-security address').output.forEach(l=>console.log('  '+l));
console.log('== dump:'); e.a.run('show running-config').output.filter(l=>/port-security/.test(l)).join('\n');
