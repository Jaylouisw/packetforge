const path=require('path');
const {Topology,Simulator}=require('../engine');const {CliSession}=require('../engine/cli');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog(path.join(__dirname,'..','devices'));
const R=c.find(s=>s.model==='generic-router'),SW=c.find(s=>s.model==='generic-switch'),PC=c.find(s=>s.model==='generic-pc');
// Two switches in a loop with a PC behind one, so STP has a blocked port and the table has entries.
const t=new Topology();const s1=t.addDevice(SW),s2=t.addDevice(SW),pc=t.addDevice(PC),r1=t.addDevice(R);
s1.name='SW1';s2.name='SW2';pc.name='PC1';r1.name='R1';
t.connect(pc.id,'eth0',s1.id,'Fa0/1');t.connect(s1.id,'Fa0/2',s2.id,'Fa0/1');t.connect(s1.id,'Fa0/3',s2.id,'Fa0/2');
t.connect(s2.id,'Fa0/3',r1.id,'Gi0/0');
const sim=new Simulator(t);const mk=d=>{const s=new CliSession(d,t,sim);s.run('enable');return s;};
const a=mk(s1),b=mk(s2),sp=mk(pc),r=mk(r1);
const cfg=(s,cmds)=>{s.run('configure terminal');cmds.forEach(x=>{const o=s.run(x).output;if(o.some(l=>/^%/.test(l)))console.log('  REFUSED '+x+' => '+o.join(' / '));});s.run('end');};
cfg(a,['hostname SW1']);cfg(b,['hostname SW2']);
cfg(sp,['hostname PC1','interface eth0','ip address 10.0.0.50 255.255.255.0','ip default-gateway 10.0.0.1','exit']);
cfg(r,['hostname R1','interface Gi0/0','ip address 10.0.0.1 255.255.255.0','exit']);
sp.run('ping 10.0.0.1 count 1');
const show=(s,x)=>{console.log('['+(s.device.config.hostname||s.device.name)+'] $ '+x);const o=s.run(x).output;o.forEach(l=>console.log('   '+l));if(!o.length)console.log('   (SILENT)');};
show(a,'show spanning-tree summary');
show(a,'show spanning-tree root');
show(b,'show spanning-tree root');
show(a,'show mac address-table count');
show(a,'show mac address-table dynamic');
show(a,'show mac address-table vlan 1');
show(a,'show mac address-table static');
show(a,'show spanning-tree bogus');
show(a,'show mac address-table bogus');
show(r,'show ip arp 10.0.0.50');
show(r,'show ip arp 10.0.0.99');
show(r,'show ip arp 10.0.0.50 extra');
show(r,'show spanning-tree summary');
