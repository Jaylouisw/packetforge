const path=require('path');
const {Topology,Simulator}=require('../engine');const {CliSession}=require('../engine/cli');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog(path.join(__dirname,'..','devices'));
const pse=c.find(d=>/2530-8-PoE/.test(d.model)), pd=c.find(d=>/EP-R6/.test(d.model)), sw=c.find(d=>d.model==='generic-switch');
const t=new Topology();const s1=t.addDevice(pse),ap=t.addDevice(pd),ap2=t.addDevice(pd),g=t.addDevice(sw);
s1.name='SW1';ap.name='AP1';ap2.name='AP2';g.name='SW2';
const poePorts=Array.from(s1.interfaces.values()).filter(i=>i.hardware&&i.hardware.poeOut).map(i=>i.name);
t.connect(ap.id,'eth0',s1.id,poePorts[0]);t.connect(ap2.id,'eth0',s1.id,poePorts[1]);
const sim=new Simulator(t);const mk=d=>{const s=new CliSession(d,t,sim);s.run('enable');return s;};
const s=mk(s1),sg=mk(g);
const show=x=>{const o=s.run(x).output;console.log('$ '+x);o.forEach(l=>console.log('  '+l));};
const cfg=(x)=>{const o=s.run(x).output;console.log('cfg '+x+' => '+(o.join(' | ')||'(silent)'));};
show('show power inline');
s.run('configure terminal'); s.run('interface '+poePorts[0]);
cfg('power inline never'); cfg('power inline static'); cfg('power inline bogus'); cfg('power inline');
s.run('end');
show('show power inline');
console.log('AP1 unpowered:', ap.poeUnpowered, ' AP2 unpowered:', ap2.poeUnpowered);
show('show power inline '+poePorts[0]);
s.run('configure terminal'); s.run('interface '+poePorts[0]); cfg('no power inline'); s.run('end');
show('show power inline');
// a device with no PoE at all
sg.run('configure terminal'); sg.run('interface Fa0/1');
const r=sg.run('power inline never').output; console.log('SW2 Fa0/1 => '+r.join(' | '));
sg.run('end');
console.log('--- running-config interface block:');
s.run('configure terminal'); s.run('interface '+poePorts[1]); s.run('power inline never'); s.run('end');
const rc=s.run('show running-config').output.join('\n');
console.log(rc.split('\n').filter(l=>/interface|power inline/.test(l)).join('\n'));
