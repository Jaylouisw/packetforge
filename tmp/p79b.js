const path=require('path');
const {Topology,Simulator}=require('../engine');const {CliSession}=require('../engine/cli');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog(path.join(__dirname,'..','devices'));
const R=c.find(s=>s.model==='generic-router'),PC=c.find(s=>s.model==='generic-pc'),SRV=c.find(s=>s.model==='generic-server');
console.log('server model?', SRV&&SRV.model);
const t=new Topology();const r=t.addDevice(R),pc=t.addDevice(PC);
r.name='R1';pc.name='PC1';
t.connect(pc.id,'eth0',r.id,'Gi0/0');
const sim=new Simulator(t);const mk=d=>{const s=new CliSession(d,t,sim);s.run('enable');return s;};
const a=mk(r),sp=mk(pc);
const cfg=(s,cm)=>{s.run('configure terminal');const o=[];for(const x of cm)o.push.apply(o,s.run(x).output);s.run('end');return o;};
cfg(sp,['hostname PC1','interface eth0','ip address 10.0.0.50 255.255.255.0','ip default-gateway 10.0.0.1','exit']);
cfg(a,['hostname R1','interface Gi0/0','ip address 10.0.0.1 255.255.255.0','exit']);
console.log('zone:', cfg(a,['dns zone lab.test']).join(' | '));
console.log('rec :', cfg(a,['dns add www.lab.test A 10.0.0.50']).join(' | '));
const show=(s,x)=>{const o=s.run(x).output;console.log('$ '+x);o.forEach(l=>console.log('  '+l));};
show(sp,'ping www.lab.test count 1');
console.log('== domain-name:');
console.log(cfg(a,['ip domain-name lab.test']).join(' | '));
show(sp,'ping www count 1');
show(a,'show dns');
console.log('== no ip domain-lookup:');
console.log(cfg(sp,['no ip domain-lookup']).join(' | '));
show(sp,'ping www count 1');
show(sp,'ping 10.0.0.1 count 1');
console.log(cfg(sp,['ip domain-lookup']).join(' | '));
show(sp,'ping www count 1');
console.log('== bad domain names:');
console.log(cfg(sp,['ip domain-name bad..name']).join(' | '));
console.log(cfg(sp,['ip domain-name -x.test']).join(' | '));
console.log(cfg(sp,['ip domain-name ok-name.test']).join(' | '));
console.log('== dump:'); console.log(sp.run('show running-config').output.filter(l=>/domain/.test(l)).join('\n'));
