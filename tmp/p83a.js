const path=require('path');
const {Topology,Simulator}=require('../engine');const {CliSession}=require('../engine/cli');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog(path.join(__dirname,'..','devices'));
const SW=c.find(s=>s.model==='generic-switch'),PC=c.find(s=>s.model==='generic-pc');
function lab(){
  const t=new Topology();const sw=t.addDevice(SW),p1=t.addDevice(PC);sw.name='SW1';p1.name='PC1';
  const ports=Array.from(sw.interfaces.keys()).filter(n=>!sw.interfaces.get(n).svi&&!sw.interfaces.get(n).parent);
  t.connect(p1.id,'eth0',sw.id,ports[0]);
  const sim=new Simulator(t);const mk=d=>{const s=new CliSession(d,t,sim);s.run('enable');return s;};
  const a=mk(sw),s1=mk(p1);
  const cfg=(s,cm)=>{s.run('configure terminal');const o=[];for(const x of cm)o.push.apply(o,s.run(x).output);s.run('end');return o;};
  cfg(s1,['hostname PC1','interface eth0','ip address 10.0.0.50 255.255.255.0','exit']);
  const speak=(port,mac,atMs)=>{ if(atMs!==undefined) sim.setRunTime(atMs);
    const f={etherType:0x0806,srcMac:mac,dstMac:'ff:ff:ff:ff:ff:ff',arp:{op:'request',senderMac:mac,senderIp:'10.0.0.9',targetMac:'00:00:00:00:00:00',targetIp:'10.0.0.254'}};
    const n=(sim.events||[]).length; sim._processFrame(sw,f,port);
    return (sim.events||[]).slice(n).map(x=>x.type+(x.mac?'('+x.mac+')':''));
  };
  return {t,sim,sw,p1,a,cfg,port:ports[0],speak,mac:p1.interfaces.get('eth0').mac};
}
const e=lab();
console.log('== configure aging:');
e.cfg(e.a,['interface '+e.port,'switchport mode access','switchport port-security','switchport port-security aging time 1','switchport port-security aging type inactivity']);
console.log('== detail:'); e.a.run('show port-security interface '+e.port).output.filter(l=>/Aging/.test(l)).forEach(l=>console.log('  '+l));
console.log('== learn at t=0:', e.speak(e.port,e.mac,0).join(','));
console.log('== seen again at t=50s:', e.speak(e.port,e.mac,50000).join(','));
console.log('== at t=110s (inactivity: 60s since last seen -> aged out):');
e.sim.setRunTime(110000);
e.a.run('show port-security address').output.forEach(l=>console.log('  '+l));
console.log('== the slot is free: a new station may be learned');
console.log('  ', e.speak(e.port,'02:00:00:00:99:99',110000).join(','));
e.a.run('show port-security').output.forEach(l=>console.log('  '+l));
console.log('== absolute type: same timeline keeps the address (clock started at 0)');
const f=lab();
f.cfg(f.a,['interface '+f.port,'switchport mode access','switchport port-security','switchport port-security aging time 1']);
f.speak(f.port,f.mac,0); f.speak(f.port,f.mac,50000);
f.sim.setRunTime(110000);
f.a.run('show port-security address').output.forEach(l=>console.log('  '+l));
console.log('== 0 aging = never:');
