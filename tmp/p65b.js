const {Topology,Simulator,CliSession}=require('../engine');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog('C:/Users/jay/packetforge/devices');
const R=c.find(s=>s.model==='generic-router'),SW=c.find(s=>s.model==='generic-switch');
const t=new Topology();const r1=t.addDevice(R);r1.name='R1';const sw=t.addDevice(SW);sw.name='SW1';const r2=t.addDevice(R);r2.name='R2';
t.connect(r1.id,'Gi0/0',sw.id,'Fa0/1');t.connect(sw.id,'Fa0/2',r2.id,'Gi0/0');const sim=new Simulator(t);
const cfg=(d,cmds,cap)=>{const s=new CliSession(d,t,sim);s.run('enable');s.run('configure terminal');for(const x of cmds){const o=s.run(x).output;if(cap&&o.some(l=>/^%/.test(l)))cap.push(x+' => '+o[0]);}s.run('end');return s;};
const bad=[];
cfg(sw,['vlan 10','interface Fa0/1','switchport mode trunk','switchport trunk allowed vlan 10','exit','interface Fa0/2','switchport mode trunk','switchport trunk allowed vlan 10','exit'],bad);
const s=cfg(r1,['interface Gi0/0.10','ip address 10.10.0.1 255.255.255.0','exit'],bad);
cfg(r2,['interface Gi0/0.10','ip address 10.10.0.2 255.255.255.0','exit'],bad);
if (bad.length) console.log('CONFIG REFUSED:', bad.join(' | '));
s.run('ping 10.10.0.2 count 2');
const show=(x)=>{console.log('$ '+x);s.run(x).output.forEach(l=>console.log('   '+l));};
show('show interfaces Gi0/0.10');
console.log('--- pull the cable');
const linkId = t.links ? (Array.from(t.links.values?t.links.values():t.links)[0].id) : null;
console.log('link id:', linkId);
s.run('link down '+linkId);
show('show ip interface brief Gi0/0.10');
show('show interfaces Gi0/0.10');
s.run('link up '+linkId);
show('show ip interface brief Gi0/0.10');
