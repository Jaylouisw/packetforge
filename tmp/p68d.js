const state=(s)=>{const o=s.run('show vrrp').output.filter(l=>/^Gi0/.test(l))[0]||'';const w=o.trim().split(/\s{2,}/);return w[3]+'/'+w[4];};
console.log('before:', state(s1), '|', state(s2));
s1.run('link down '+l1.id);
console.log('down  :', state(s1), '|', state(s2));
s1.run('link up '+l1.id);
console.log('up    :', state(s1), '|', state(s2));
const counters=(s)=>{const o=s.run('show interfaces counters').output.join('\n');return o;};
const s3=new CliSession(r1,t,sim);s3.run('enable');
console.log('counters before self-ping:', s3.run('show interfaces counters Gi0/0').output.join('|'));
s3.run('ping 192.168.9.2 count 2');
console.log('counters after self-ping :', s3.run('show interfaces counters Gi0/0').output.join('|'));
