const {Topology,Simulator,CliSession}=require('../engine');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog('C:/Users/jay/packetforge/devices');
const R=c.find(s=>s.model==='generic-router');
const t=new Topology();const r1=t.addDevice(R);r1.name='R1';const r2=t.addDevice(R);r2.name='R2';
t.connect(r1.id,'Gi0/0',r2.id,'Gi0/0');const sim=new Simulator(t);
const cfg=(d,cmds)=>{const s=new CliSession(d,t,sim);s.run('enable');s.run('configure terminal');for(const x of cmds){const o=s.run(x).output;if(o.some(l=>/^%/.test(l)))console.log('  REFUSED ['+d.name+'] '+x+' => '+o[0]);}s.run('end');return s;};
const s1=cfg(r1,['ipv6 unicast-routing','interface Gi0/0','ipv6 address 2001:db8:1::1/64','exit']);
cfg(r2,['ipv6 unicast-routing','interface Gi0/0','ipv6 address 2001:db8:1::2/64','exit']);
const rate=(o)=>{const m=/Success rate is (\d+) percent/.exec(o.join(' '));return m?m[1]+'%':'?';};
const p=(s,x)=>{const o=s.run(x).output;console.log('$ '+x);o.forEach(l=>console.log('   '+l));return o;};
console.log('ping r2:', rate(s1.run('ping ipv6 2001:db8:1::2 count 2').output));
const s2=new CliSession(r2,t,sim);s2.run('enable');
s2.run('configure terminal');p(s2,'no ipv6 unicast-routing');s2.run('end');
console.log('ping after disable:', rate(s1.run('ping ipv6 2001:db8:1::2 count 2').output));
p(s2,'show ipv6 route');
s2.run('configure terminal');p(s2,'ipv6 unicast-routing');s2.run('end');
console.log('ping after enable:', rate(s1.run('ping ipv6 2001:db8:1::2 count 2').output));
p(s1,'show ipv6 interface brief');
p(s1,'show ipv6 interface brief Gi0/0');
console.log('--- mode keeping:');
const s3=new CliSession(r1,t,sim);s3.run('enable');s3.run('configure terminal');s3.run('interface Gi0/0');
p(s3,'ipv6 nd suppress-ra extra');
console.log('  mode now:', s3.mode);
p(s3,'ipv6 nd ra enable');
p(s3,'ipv6 unicast-routing');
console.log('  mode now:', s3.mode);
