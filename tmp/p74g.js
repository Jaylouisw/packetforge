const path=require('path');
const {Topology,Simulator}=require('../engine');const {CliSession}=require('../engine/cli');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog(path.join(__dirname,'..','devices'));const R=c.find(s=>s.model==='generic-router'),PC=c.find(s=>s.model==='generic-pc');
const t=new Topology();const pc=t.addDevice(PC);const r=t.addDevice(R);
t.connect(pc.id,'eth0',r.id,'Gi0/0');
const sim=new Simulator(t);const sp=new CliSession(pc,t,sim);sp.run('enable');
sp.run('configure terminal');sp.run('interface eth0');sp.run('ip address 10.0.0.50 255.255.255.0');sp.run('exit');sp.run('end');
const a=new CliSession(r,t,sim);a.run('enable');a.run('configure terminal');a.run('interface Gi0/0');a.run('ip address 10.0.0.1 255.255.255.0');a.run('end');
console.log('--- flow open:');sp.run('flow open 10.0.0.1 bytes 4000').output.forEach(l=>console.log('  '+l));
console.log('--- show flows:');a.run('show flows').output.slice(0,8).forEach(l=>console.log('  '+l));
