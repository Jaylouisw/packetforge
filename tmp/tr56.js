const {Topology,Simulator,CliSession}=require('../engine');const {loadCatalog}=require('../devices/registry');
const c=loadCatalog('C:/Users/jay/packetforge/devices');
const SW=c.find(s=>s.model==='generic-switch'),R=c.find(s=>s.model==='generic-router');
const t=new Topology();const sw=t.addDevice(SW);sw.name='SW1';const s=new CliSession(sw,t,new Simulator(t));s.run('enable');s.run('configure terminal');
const C=(x)=>{console.log('SW1(config)#'+x); s.run(x).output.forEach(l=>console.log(l));};
const I=(x)=>{console.log('SW1(config-if)#'+x); s.run(x).output.forEach(l=>console.log(l));};
C('interface Fa0/1');
I('switchport access vlan abc');
I('switchport access vlan 10 20');
I('switchport');
I('switchport trunk allowed');
I('switchport mode trunk');
I('switchport trunk native vlan 99');
I('switchport trunk allowed vlan 10,20,30');
I('no switchport trunk allowed vlan 10');
console.log('SW1#show running-config (Fa0/1 block)');
s.run('end');
s.run('show running-config').output.filter(l=>/interface Fa0\/1/.test(l)||/switchport/.test(l)).slice(0,6).forEach(l=>console.log(l));
console.log('--- router and SVI ---');
const t2=new Topology();const r=t2.addDevice(R);r.name='R1';const s2=new CliSession(r,t2,new Simulator(t2));s2.run('enable');s2.run('configure terminal');
console.log('R1(config)#interface Gi0/0'); s2.run('interface Gi0/0').output.forEach(l=>console.log(l));
console.log('R1(config-if)#switchport access vlan 10'); s2.run('switchport access vlan 10').output.forEach(l=>console.log(l));
const s3=new CliSession(sw,t,new Simulator(t)); s3.run('enable'); s3.run('configure terminal'); s3.run('vlan 10'); s3.run('interface vlan 10');
console.log('SW1(config-if)#switchport access vlan 10  (on Vlan10)'); s3.run('switchport access vlan 10').output.forEach(l=>console.log(l));
